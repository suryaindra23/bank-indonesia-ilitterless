ALTER TABLE bibu.verified_accounts ENABLE ROW LEVEL SECURITY;
ALTER TABLE bibu.account_roles ENABLE ROW LEVEL SECURITY;
ALTER TABLE bibu.email_tokens ENABLE ROW LEVEL SECURITY;
ALTER TABLE bibu.migration_history ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON ALL TABLES IN SCHEMA bibu FROM PUBLIC;

 CREATE TABLE IF NOT EXISTS bibu.super_admins(uid TEXT PRIMARY KEY REFERENCES bibu.accounts(id),granted_by TEXT NOT NULL,created TEXT NOT NULL);
 CREATE TABLE IF NOT EXISTS bibu.role_changes(id TEXT PRIMARY KEY,actor_id TEXT NOT NULL,actor_email TEXT NOT NULL,target_id TEXT NOT NULL,target_email TEXT NOT NULL,before_roles TEXT NOT NULL,after_roles TEXT NOT NULL,created TEXT NOT NULL);
ALTER TABLE bibu.super_admins ENABLE ROW LEVEL SECURITY;
