CREATE SCHEMA IF NOT EXISTS bibu;
CREATE TABLE IF NOT EXISTS bibu.accounts(id TEXT PRIMARY KEY,email TEXT UNIQUE NOT NULL,name TEXT NOT NULL,loc TEXT NOT NULL,role TEXT NOT NULL,password_hash TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS bibu.sessions(token_hash TEXT PRIMARY KEY,uid TEXT NOT NULL REFERENCES bibu.accounts(id),expires BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS bibu.state(id INTEGER PRIMARY KEY CHECK(id=1),data TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS bibu.audit(id BIGSERIAL PRIMARY KEY,uid TEXT NOT NULL,action TEXT NOT NULL,created TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS bibu.verified_accounts(uid TEXT PRIMARY KEY REFERENCES bibu.accounts(id));
CREATE TABLE IF NOT EXISTS bibu.account_roles(uid TEXT NOT NULL REFERENCES bibu.accounts(id),role TEXT NOT NULL CHECK(role IN ('peserta','admin','bi')),PRIMARY KEY(uid,role));
CREATE TABLE IF NOT EXISTS bibu.email_tokens(token_hash TEXT PRIMARY KEY,uid TEXT NOT NULL REFERENCES bibu.accounts(id),purpose TEXT NOT NULL,expires BIGINT NOT NULL,created BIGINT NOT NULL);
CREATE INDEX IF NOT EXISTS sessions_uid_idx ON bibu.sessions(uid);
CREATE INDEX IF NOT EXISTS sessions_expires_idx ON bibu.sessions(expires);
CREATE INDEX IF NOT EXISTS email_tokens_uid_idx ON bibu.email_tokens(uid,purpose);
REVOKE ALL ON SCHEMA bibu FROM PUBLIC;

CREATE TABLE IF NOT EXISTS bibu.migration_history(id INTEGER PRIMARY KEY CHECK(id=1),source_hash TEXT NOT NULL,created TEXT NOT NULL,counts TEXT NOT NULL);

ALTER TABLE bibu.accounts ENABLE ROW LEVEL SECURITY;
